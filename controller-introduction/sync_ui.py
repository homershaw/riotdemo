"""Refresh presentation assets from current Nano source; never writes firmware."""
import argparse
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent


def extract(source, marker):
    matches = re.findall(r'R"' + re.escape(marker) + r'\((.*?)\)' + re.escape(marker) + '"', source, re.S)
    if len(matches) != 1:
        raise ValueError(f"Expected one {marker} raw literal; found {len(matches)}")
    return matches[0]


def sync(source_path):
    source = source_path.read_text(encoding="utf-8")
    assets = {
        "riot.css": extract(source, "CSS"),
        "dashboard.html": extract(source, "DASHC") + extract(source, "UXJ") + "</script>",
        "dashboard-layout.html": extract(source, "DBLAY").replace("</body></html>", ""),
    }
    for name, text in assets.items():
        (HERE / "web" / name).write_text(
            ("/* Generated by sync_ui.py; do not hand-edit. */\n" if name.endswith(".css")
             else "<!-- Generated by sync_ui.py; do not hand-edit. -->\n") + text,
            encoding="utf-8",
        )
        print(f"Generated web\\{name}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    # The controller source is in the private Riot repo; by default a P4 checkout next to riotdemo.
    parser.add_argument("--source", type=Path, default=HERE.parents[1] / "P4" / "firmware" / "src" / "riot_p4.cpp")
    sync(parser.parse_args().source)
